<div class="prose">
  <h2>Catálogo e imagens</h2>
  <p>
    <a href="https://github.com/PokeAPI/pokeapi">PokéAPI</a>: dados de espécies,
    formas, golpes, itens, habilidades e jogos.
    <a href="https://github.com/PokeAPI/sprites">PokéAPI/sprites</a>: sprites e
    artes e símbolos de tipos extraídos dos jogos. As tipagens usam as imagens de Sword/Shield; Stellar usa Scarlet/Violet. Ícones de categorias de golpes e sprites
    complementares de itens vêm do acervo Pokémon Showdown. Habilidades sem
    sprite específico usam ícones de interface Lucide. A revisão importada está
    na página de
    <a href="/cobertura">cobertura</a>.
  </p>
  <h2>Regras e cálculos</h2>
  <p>
    <a href="https://github.com/smogon/pokemon-showdown">Pokémon Showdown</a>:
    regras de formatos, validação e simulação.
    <a href="https://github.com/smogon/damage-calc">Smogon Damage Calculator</a
    >: atributos e dano.
  </p>
  <h2>Builds de referência</h2>
  <p>
    <a href="https://github.com/pkmn/smogon">pkmn/smogon</a> disponibiliza dados derivados
    de sets e análises de Smogon. Os sets e análises pertencem à Smogon e aos seus
    contribuidores. Cada build importada mantém seu link de origem; as explicações
    exibidas pelo illke são próprias.
  </p>
  <h2>Comunidade</h2>
  <p>
    Builds, equipes e mensagens publicadas por usuários mantêm a identificação
    de seus autores. Votos da comunidade não representam resultados de
    simulação.
  </p>
  <h2>Direitos</h2>
  <p>
    Pokémon e seus personagens pertencem aos respectivos titulares. O illke é um
    projeto independente de fãs, sem vínculo oficial com a franquia.
  </p>
</div>

<section class="prose" id="mapas"><h2>Mapas e coordenadas</h2><p>Mapas regionais clássicos provenientes das reconstruções de <a href="https://github.com/pret">pret</a>, distribuídos pelo <a href="https://github.com/paulthemagno/pokemon-emulator-tracker">Pokémon Emulator Tracker</a>. Os arquivos são servidos localmente; a revisão e as origens estão no <a href="/maps/sources.json">manifesto dos mapas</a>. As marcações representam áreas regionais e não posições exatas dentro da rota. Nas demais regiões, a arte regional é uma referência visual e não confirma coordenadas ou diferenças entre edições. As respectivas fontes são indicadas junto à imagem.</p><p>As imagens de Pokémon e dos jogos pertencem a Nintendo, Creatures e GAME FREAK. Este é um projeto independente de fãs.</p></section>
<section class="prose" id="jogos"><h2>Jogos e cobertura das pistas</h2><p>O catálogo reúne a série principal, derivados e aplicativos. Plataformas indicam as edições nativas. Relançamentos e retrocompatibilidade não são uma lista de compatibilidade de hardware. <a href="https://www.pokemon.com/us/pokemon-video-games">Catálogo oficial Pokémon</a>.</p><p>Encontros e itens usam a <a href="https://pokeapi.co/docs/v2/">PokéAPI</a>, consultada no servidor e mantida em cache por até 24 horas. Ausência de encontros não comprova indisponibilidade. Portadores de itens, lojas, eventos, transferências e DLCs têm cobertura desigual. Winds e Waves estão anunciados para 2027, conforme a <a href="https://www.nintendo.com/ph/news/article/7exdME3HEo60PDMCF8DyQ2">Nintendo</a>.</p></section>

<p class="help">Itens no cenário de FireRed/LeafGreen e Emerald: extração de eventos explícitos dos projetos pret/pokefirered e pret/pokeemerald. Revisões fixadas no snapshot local. Presentes de NPCs, lojas e scripts condicionais não são inferidos.</p>

<section class="prose"><h2>Imagens dos consoles</h2><p>Imagens existentes do pacote <a href="https://github.com/libretro/retroarch-assets">RetroArch assets / FlatUX</a>, por baxysquare e contribuidores do RetroArch, sob <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>. PC e celular usam <a href="https://github.com/jdecked/twemoji">Twemoji</a>, por Twitter, Inc. e contribuidores, sob a mesma licença. Os arquivos são usados sem alterações. <a href="/consoles/sources.json">Arquivos, revisão e créditos</a>.</p></section>

<section class="prose"><h2>Mapas locais e capas</h2><p>Os cenários locais são reconstruídos dos tiles, paletas e layouts de <a href="https://github.com/pret/pokefirered">pret/pokefirered</a> e <a href="https://github.com/pret/pokeemerald">pret/pokeemerald</a>, nas revisões fixadas do snapshot de itens. <a href="/maps/local/sources.json">Fontes dos cenários</a>. São imagens do jogo; personagens móveis não aparecem. As capas são digitalizações do acervo <a href="https://github.com/libretro-thumbnails">Libretro thumbnails</a>. Artes promocionais e ícones de apps vêm do <a href="https://www.pokemon.co.jp/game/">catálogo oficial japonês Pokémon</a>. A interface distingue capas de artes oficiais. <a href="/covers/sources.json">Fontes das imagens</a>.</p></section>
