  <h1>Fontes e créditos</h1>
  <p>Origem dos dados, imagens e cálculos.</p>
</div>
<div class="prose">
  <h2>Catálogo e imagens</h2>
  <p>
    <a href="https://github.com/PokeAPI/pokeapi">PokéAPI</a>: dados de espécies,
    formas, golpes, itens, habilidades e jogos.
    <a href="https://github.com/PokeAPI/sprites">PokéAPI/sprites</a>: sprites e
    artes. A revisão importada está na página de
    <a href="/cobertura">cobertura</a>.
  </p>
  <h2>Regras e cálculos</h2>
  <p>
    <a href="https://github.com/smogon/pokemon-showdown">Pokémon Showdown</a>:
    regras de formatos, validação e simulação.
    <a href="https://github.com/smogon/damage-calc">Smogon Damage Calculator</a
    >: atributos e dano.
  </p>
  <h2>Builds de referência</h2>
  <p>
    <a href="https://github.com/pkmn/smogon">pkmn/smogon</a> disponibiliza dados derivados
    de sets e análises de Smogon. Os sets e análises pertencem à Smogon e aos seus
    contribuidores. Cada build importada mantém seu link de origem; as explicações
    exibidas pelo illke são próprias.
  </p>
  <h2>Comunidade</h2>
  <p>
    Builds, equipes e mensagens publicadas por usuários mantêm a identificação
    de seus autores. Votos da comunidade não representam resultados de
    simulação.
  </p>
  <h2>Direitos</h2>
  <p>
    Pokémon e seus personagens pertencem aos respectivos titulares. O illke é um
    projeto independente de fãs, sem vínculo oficial com a franquia.
  </p>
</div>
